/**
 * Keyword rules, checked in order. Game designers use the design vocabulary; other game roles go to generic,
 * and specific specialisms (energy, healthcare, finance) win over generic words like "engineer".
 */
const RULES: [FamilyId, RegExp][] = [
  ["design", /\b(game|level|narrative|systems) designer\b/],
  ["generic", /\bgames?\b|\bgaming\b/],
  ["ai_ml", /\bai\b|\bml\b|machine learning|\bllms?\b|prompt|mlops|artificial intelligence|deep learning|\bnlp\b/],
  ["energy_eng", /energy|utilit|\bpower\b|\boil\b|\bgas\b|renewabl|solar|\bwind\b|mechanical|civil|electrical|electrician|lineworker|lineman|hvac|millwright|instrumentation|environmental|sustainab|petroleum/],
  ["healthcare", /nurs|clinical|health|\bcare\b|pharmac|medic|physician|therap|paramedic|dental/],
  ["finance", /financ|accountant|accounting|fp&a|\baudit|controller|investment|treasury|bookkeep/],
  ["people", /\bhr\b|recruit|people|talent|l&d|human resources|learning and development/],
  ["design", /designer|\bux\b|\bui\b|user research|product design|visual design/],
  ["product", /product manager|product owner|product lead|product management|\bpm\b|program manager/],
  ["marketing", /marketing|growth|\bseo\b|content|\bbrand|social|communications|\bpr\b|copywrit|advertis/],
  ["sales_cs", /sales|account executive|business development|customer success|account manager|support/],
  ["operations", /operations|\bops\b|supply chain|logistic|project manager|coordinator|procurement|warehouse/],
  ["data", /\bdata\b|analyst|analytics|\bbi\b|scientist|statistic|quant/],
  ["software", /engineer|developer|backend|frontend|full stack|devops|\bsre\b|mobile|\bios\b|android|programmer|\bqa\b|software/],
];

/** Picks the role family for a target role. Defaults to generic. */
export function detectFamily(targetRole: string): FamilyId {
  const text = targetRole.toLowerCase();
  for (const [id, rule] of RULES) if (rule.test(text)) return id;
  return "generic";
}
