/** Picks the industry pack for free text. Falls back to generic services. */
export function detectDomain(industry: string | undefined): Domain {
  const text = (industry ?? "").toLowerCase();
  if (!text.trim()) return DOMAINS[DOMAINS.length - 1];
  return DOMAINS.find((d) => d.id !== "generic" && d.match.test(text)) ?? DOMAINS[DOMAINS.length - 1];
}
